"""Run the surrogate sweep, save results/lumped_sweep.json, and write docs/assets/data.js for the live page
(window.TR4680 = {matrix, scaling, lumped}). Everything the page shows comes from this file."""
from __future__ import annotations
import json, time
import numpy as np
from . import ROOT, ASSETS
from . import matrix as mx, scaling as sc
from .lumped import Params, simulate

COUPLING_SCALE = 3.0           # the one calibrated parameter; see README "Reduced-order surrogate" and docs/CLAIMS.md
K_VALUES = (0.5, 0.75, 1.0, 1.25, 1.5, 2.0)
H_VALUES = (0, 100, 500, 2000)


def run_sweep(scale=COUPLING_SCALE, k_values=K_VALUES, h_values=H_VALUES, verbose=True):
    sweep, traces = [], {}
    for h in h_values:
        for k in k_values:
            t0 = time.time(); r = simulate(Params(k_tl=k, h_plate=h, coupling_scale=scale))
            key = f"h{h}_k{k:g}"
            sweep.append({"h_plate": h, "k_tl": k, "n_ignited": r.n_ignited, "cascade": r.cascade, "second_ignition_min": None if r.second_ignition_min is None else round(r.second_ignition_min, 2),
                          "neighbour_peak_C": round(float(r.cell_max[:, 1].max()), 1), "pack_mean_end_C": round(float(r.cell_mean[-1].mean()), 1)})
            if h in (0, 2000):  # traces for the live page: every 10 s, per-cell maximum temperature
                traces[key] = {"t_min": (r.t[::10] / 60).round(3).tolist(), "cell_max_C": r.cell_max[::10].round(1).tolist(), "ignition_min": [None if v is None else round(v / 60, 2) for v in r.ignition_s]}
            if verbose: print(f"  h={h:5d} k={k:4.2f}: {'cascade' if r.cascade else 'arrested'} n={r.n_ignited:2d} 2nd={sweep[-1]['second_ignition_min']} nb_peak={sweep[-1]['neighbour_peak_C']} [{time.time()-t0:.1f}s]")
    base = simulate(Params(k_tl=1.0, h_plate=2000, coupling_scale=scale, r_cap=1e-3)); tabless = simulate(Params(k_tl=1.0, h_plate=2000, coupling_scale=scale, r_cap=1e-5))
    rcap = {"tabbed_R_cap_1e-3": {"second_ignition_min": base.second_ignition_min, "neighbour_peak_C": round(float(base.cell_max[:, 1].max()), 2)},
            "tabless_R_cap_1e-5": {"second_ignition_min": tabless.second_ignition_min, "neighbour_peak_C": round(float(tabless.cell_max[:, 1].max()), 2)}}
    out = {"description": "Reduced-order lumped network surrogate built in this repository (analysis/lumped.py). NOT the COMSOL model. One calibrated parameter: coupling_scale.",
           "coupling_scale": scale, "k_values": list(k_values), "h_values": list(h_values), "sweep": sweep, "traces": traces,
           "trace_cascade": "h2000_k1", "trace_arrest": "h2000_k1.25", "contact_resistance_check": rcap,
           "params_default": {k: (list(v) if isinstance(v, tuple) else v) for k, v in Params().__dict__.items()}}
    (ROOT / "results").mkdir(exist_ok=True)
    with open(ROOT / "results" / "lumped_sweep.json", "w") as f: json.dump(out, f, indent=1)
    return out


def write_data_js(lumped=None):
    m = mx.load()
    if lumped is None:
        with open(ROOT / "results" / "lumped_sweep.json") as f: lumped = json.load(f)
    data = {"matrix": m, "scaling": sc.summary(), "lumped": lumped}
    ASSETS.mkdir(parents=True, exist_ok=True)
    with open(ASSETS / "data.js", "w", encoding="utf-8") as f:
        f.write("// Generated by python -m analysis.export from results/matrix.json, analysis/scaling.py and results/lumped_sweep.json. Do not edit by hand.\n")
        f.write("window.TR4680 = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", ASSETS / "data.js", (ASSETS / "data.js").stat().st_size, "bytes")


if __name__ == "__main__":
    import sys
    lumped = run_sweep() if "--no-sweep" not in sys.argv else None
    write_data_js(lumped)
